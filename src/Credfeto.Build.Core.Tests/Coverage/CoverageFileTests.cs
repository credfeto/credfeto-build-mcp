using System;
using Credfeto.Build.Core.Coverage;
using FunFair.Test.Common;
using Xunit;

namespace Credfeto.Build.Core.Tests.Coverage;

public sealed class CoverageFileTests : TestBase
{
    private const string SHA = "0123456789abcdef0123456789abcdef01234567";

    private const string SECTION =
        "## .NET\n\n| Project | Line Coverage |\n| --- | --- |\n| Example.Core | 80.0% |\n| **Overall (.NET)** | **80.0%** |\n";

    private const string HEADER = "# Coverage\n\nGenerated by the AI Coverage phase. Do not edit by hand.\n\n";

    private const string OTHER_SECTIONS =
        "## Node\n\nn/a (no code)\n\n## Python\n\nn/a (no code)\n\n## Shell\n\nexcluded\n\n";

    private static readonly DateOnly CapturedOn = new(year: 2026, month: 11, day: 15);

    [Fact]
    public static void AMissingFileGetsOnlyTheDotnetSectionAndTheCommitLine()
    {
        Assert.Equal(
            expected: HEADER + SECTION + "\n---\n\nCaptured at commit `" + SHA + "` on 2026-11-15.\n",
            actual: Merge(null)
        );
    }

    [Fact]
    public static void OnlyTheDotnetSectionAndTheCommitLineChange()
    {
        const string existing =
            HEADER
            + "## .NET\n\n| Component | Line coverage |\n| --- | --- |\n| Old.Project | 12.34% |\n| **Overall** | **12.34%** |\n\n"
            + OTHER_SECTIONS
            + "---\n\nCaptured at commit `777c08b0000000000000000000000000000000aa` on 2026-11-14.\n";

        Assert.Equal(
            expected: HEADER
                + SECTION
                + "\n"
                + OTHER_SECTIONS
                + "---\n\nCaptured at commit `"
                + SHA
                + "` on 2026-11-15.\n",
            actual: Merge(existing)
        );
    }

    [Fact]
    public static void MergingTwiceGivesTheSameFile()
    {
        const string existing = HEADER + OTHER_SECTIONS + "---\n\nCaptured at commit `old` on 2026-01-01.\n";

        string once = Merge(existing);

        Assert.Equal(expected: once, actual: Merge(once));
    }

    [Fact]
    public static void AMissingDotnetSectionGoesBeforeTheFirstOtherSection()
    {
        const string existing = HEADER + OTHER_SECTIONS + "---\n\nCaptured at commit `old` on 2026-01-01.\n";

        Assert.Equal(
            expected: HEADER
                + SECTION
                + "\n"
                + OTHER_SECTIONS
                + "---\n\nCaptured at commit `"
                + SHA
                + "` on 2026-11-15.\n",
            actual: Merge(existing)
        );
    }

    [Fact]
    public static void AMissingDotnetSectionGoesBeforeTheFooterRuleWhenThereAreNoOtherSections()
    {
        const string existing = HEADER + "---\n\nCaptured at commit `old` on 2026-01-01.\n";

        Assert.Equal(
            expected: HEADER + SECTION + "\n---\n\nCaptured at commit `" + SHA + "` on 2026-11-15.\n",
            actual: Merge(existing)
        );
    }

    [Fact]
    public static void AFileWithNoSectionsOrFooterGetsBothAppended()
    {
        Assert.Equal(
            expected: "# Coverage\n\n" + SECTION + "\n---\n\nCaptured at commit `" + SHA + "` on 2026-11-15.\n",
            actual: Merge("# Coverage")
        );
    }

    [Fact]
    public static void AFooterRuleWithoutACommitLineGetsTheCommitLine()
    {
        const string existing = HEADER + "## .NET\n\nold\n\n---\n";

        Assert.Equal(
            expected: HEADER + SECTION + "\n---\n\nCaptured at commit `" + SHA + "` on 2026-11-15.\n",
            actual: Merge(existing)
        );
    }

    [Fact]
    public static void ADotnetSectionAtTheEndIsReplacedToTheEnd()
    {
        const string existing = HEADER + OTHER_SECTIONS + "## .NET\n\nold";

        Assert.Equal(
            expected: HEADER + OTHER_SECTIONS + SECTION + "\n---\n\nCaptured at commit `" + SHA + "` on 2026-11-15.\n",
            actual: Merge(existing)
        );
    }

    [Fact]
    public static void WindowsLineEndingsAreKept()
    {
        string existing = (
            HEADER + "## .NET\n\nold\n\n" + OTHER_SECTIONS + "---\n\nCaptured at commit `old` on 2026-01-01.\n"
        ).Replace(oldValue: "\n", newValue: "\r\n", comparisonType: StringComparison.Ordinal);

        Assert.Equal(
            expected: (
                HEADER + SECTION + "\n" + OTHER_SECTIONS + "---\n\nCaptured at commit `" + SHA + "` on 2026-11-15.\n"
            ).Replace(oldValue: "\n", newValue: "\r\n", comparisonType: StringComparison.Ordinal),
            actual: Merge(existing)
        );
    }

    [Theory]
    [InlineData("dotnet")]
    [InlineData("--coverage")]
    [InlineData("reportgenerator")]
    [InlineData("cobertura")]
    public static void TheFileNeverRecordsHowItWasMeasured(string forbidden)
    {
        Assert.DoesNotContain(
            expectedSubstring: forbidden,
            actualString: Merge(null),
            comparisonType: StringComparison.OrdinalIgnoreCase
        );
    }

    private static string Merge(string? existing)
    {
        return CoverageFile.Merge(
            existing: existing,
            language: CoverageLanguage.Dotnet,
            section: SECTION,
            headSha: SHA,
            capturedOn: CapturedOn
        );
    }
}
