using System;
using System.IO;
using System.Threading.Tasks;
using Credfeto.Build.Core.Coverage;
using Credfeto.Build.Testing;
using FunFair.Test.Common;
using Xunit;

namespace Credfeto.Build.Core.Tests.Coverage;

public sealed class CoverageRowUpdateTests : TestBase
{
    private const string SHA = "0123456789abcdef0123456789abcdef01234567";

    private const string HEADER = "# Coverage\n\nGenerated by the AI Coverage phase. Do not edit by hand.\n\n";

    private const string TABLE_HEADER =
        "| Project | Line Coverage | Covered | Coverable |\n| --- | --- | --- | --- |\n";

    private const string NODE_AND_SHELL = "## Node\n\nn/a (no code)\n\n## Shell\n\nexcluded\n\n";

    private const string OLD_FOOTER = "---\n\nCaptured at commit `old` on 2026-01-01.\n";

    private const string NEW_FOOTER = "---\n\nCaptured at commit `" + SHA + "` on 2026-11-24.\n";

    private static readonly DateOnly CapturedOn = new(year: 2026, month: 11, day: 24);

    [Fact]
    public static void AFullRunWritesTheCountsOfEveryRowAndOverallIsTheirSum()
    {
        CoverageSummary summary = Summary(Measured("Example.Api", 7, 10, 70d), Measured("Example.Core", 3, 5, 60d));

        Assert.Equal(
            expected: "## .NET\n\n"
                + TABLE_HEADER
                + "| Example.Api | 70.0% | 7 | 10 |\n"
                + "| Example.Core | 60.0% | 3 | 5 |\n"
                + "| **Overall (.NET)** | **66.7%** | **10** | **15** |\n",
            actual: CoverageMarkdown.FormatSection(summary: summary, language: CoverageLanguage.Dotnet)
        );
    }

    [Fact]
    public static void AComponentWithNoCoverableLinesCountsAsNone()
    {
        CoverageSummary summary = Summary(Measured("Example.Api", 7, 10, 70d), Measured("Example.Empty", 0, 0, 0d));

        Assert.Contains(
            expectedSubstring: "| Example.Empty | 0.0% | 0 | 0 |\n| **Overall (.NET)** | **70.0%** | **7** | **10** |\n",
            actualString: CoverageMarkdown.FormatSection(summary: summary, language: CoverageLanguage.Dotnet),
            comparisonType: StringComparison.Ordinal
        );
    }

    [Fact]
    public static void ARowUpdateChangesOnlyItsRowAndOverallAndMatchesAFullRun()
    {
        string before = FullRun(Measured("Example.Api", 7, 10, 70d), Measured("Example.Core", 3, 5, 60d));
        string fullRun = FullRun(Measured("Example.Api", 7, 10, 70d), Measured("Example.Core", 5, 5, 100d));

        CoverageRowUpdate update = Update(existing: before, row: CoverageRow.Measured("Example.Core", 5, 5));

        Assert.Equal(expected: CoverageRowOutcome.OverallRecomputed, actual: update.Outcome);
        Assert.Empty(update.RowsWithoutCounts);
        Assert.Equal(expected: fullRun, actual: update.Text);
        Assert.Contains(
            expectedSubstring: "| Example.Api | 70.0% | 7 | 10 |\n| Example.Core | 100.0% | 5 | 5 |\n| **Overall (.NET)** | **80.0%** | **12** | **15** |\n",
            actualString: update.Text,
            comparisonType: StringComparison.Ordinal
        );
    }

    [Fact]
    public static void ARowUpdateAddsANewComponentInFullRunOrder()
    {
        string before = FullRun(Measured("Example.Api", 7, 10, 70d), Measured("Example.Core", 3, 5, 60d));
        string fullRun = FullRun(
            Measured("Example.Api", 7, 10, 70d),
            Measured("Example.Bravo", 1, 5, 20d),
            Measured("Example.Core", 3, 5, 60d)
        );

        CoverageRowUpdate update = Update(existing: before, row: CoverageRow.Measured("Example.Bravo", 1, 5));

        Assert.Equal(expected: CoverageRowOutcome.OverallRecomputed, actual: update.Outcome);
        Assert.Equal(expected: fullRun, actual: update.Text);
    }

    [Fact]
    public static void AFileWithoutCountsKeepsItsOverallAndNamesTheRowsThatHaveNone()
    {
        const string before =
            HEADER
            + "## .NET\n\n| Component | Line coverage |\n| --- | --- |\n| Example.Api | 70.00% |\n| Example.Core | 60.00% |\n| **Overall** | **66.67%** |\n\n"
            + NODE_AND_SHELL
            + OLD_FOOTER;

        CoverageRowUpdate update = Update(existing: before, row: CoverageRow.Measured("Example.Core", 5, 5));

        Assert.Equal(expected: CoverageRowOutcome.OverallUnchanged, actual: update.Outcome);
        Assert.Equal(expected: ["Example.Api"], actual: update.RowsWithoutCounts, comparer: StringComparer.Ordinal);
        Assert.Equal(
            expected: HEADER
                + "## .NET\n\n"
                + TABLE_HEADER
                + "| Example.Api | 70.00% | | |\n"
                + "| Example.Core | 100.0% | 5 | 5 |\n"
                + "| **Overall (.NET)** | **66.67%** | | |\n\n"
                + NODE_AND_SHELL
                + NEW_FOOTER,
            actual: update.Text
        );
    }

    [Fact]
    public static void ANotApplicableRowWithoutCountsCountsAsNoLines()
    {
        const string before =
            HEADER
            + "## .NET\n\n"
            + TABLE_HEADER
            + "| Example.Api | 70.0% | 7 | 10 |\n| Example.Empty | n/a |\n| **Overall (.NET)** | **70.0%** | **7** | **10** |\n\n"
            + OLD_FOOTER;

        CoverageRowUpdate update = Update(existing: before, row: CoverageRow.Measured("Example.Api", 9, 10));

        Assert.Equal(expected: CoverageRowOutcome.OverallRecomputed, actual: update.Outcome);
        Assert.Contains(
            expectedSubstring: "| Example.Empty | n/a | 0 | 0 |\n| **Overall (.NET)** | **90.0%** | **9** | **10** |\n",
            actualString: update.Text,
            comparisonType: StringComparison.Ordinal
        );
    }

    [Theory]
    [InlineData(HEADER + NODE_AND_SHELL + OLD_FOOTER)]
    [InlineData(HEADER + "## .NET\n\nn/a (no code)\n\n" + NODE_AND_SHELL + OLD_FOOTER)]
    [InlineData(HEADER + "## .NET\n\n" + TABLE_HEADER + "| Example.Api | 70.0% | 7 | 10 |\n\n" + OLD_FOOTER)]
    [InlineData("")]
    public static void AFileWithNoTableForTheLanguageIsNotWritten(string existing)
    {
        CoverageRowUpdate update = Update(existing: existing, row: CoverageRow.Measured("Example.Api", 9, 10));

        Assert.Equal(expected: CoverageRowOutcome.NoTable, actual: update.Outcome);
        Assert.Null(update.Text);
    }

    [Fact]
    public static void ARowUpdateLeavesTheOtherLanguagesAlone()
    {
        const string node =
            "## Node\n\n| Package | Line Coverage | Covered | Coverable |\n| --- | --- | --- | --- |\n| web | 50.0% | 1 | 2 |\n| **Overall (Node)** | **50.0%** | **1** | **2** |\n";
        string before = HEADER + Section(Measured("Example.Api", 7, 10, 70d)) + "\n" + node + "\n" + OLD_FOOTER;

        CoverageRowUpdate update = Update(existing: before, row: CoverageRow.Measured("Example.Api", 9, 10));

        Assert.Equal(
            expected: HEADER + Section(Measured("Example.Api", 9, 10, 90d)) + "\n" + node + "\n" + NEW_FOOTER,
            actual: update.Text
        );
    }

    [Fact]
    public async Task UpdatingARowRewritesTheFileAsync()
    {
        using TemporaryDirectory directory = new();
        string path = await directory.WriteAsync(
            relative: CoverageFile.FILE_NAME,
            content: FullRun(Measured("Example.Api", 7, 10, 70d)),
            cancellationToken: this.CancellationToken()
        );

        CoverageRowUpdate update = await UpdateFileAsync(path: path, cancellationToken: this.CancellationToken());

        Assert.Equal(expected: CoverageRowOutcome.OverallRecomputed, actual: update.Outcome);
        Assert.Equal(
            expected: FullRun(Measured("Example.Api", 9, 10, 90d)),
            actual: await File.ReadAllTextAsync(path: path, cancellationToken: this.CancellationToken())
        );
    }

    [Fact]
    public async Task UpdatingARowNeverCreatesAMissingFileAsync()
    {
        using TemporaryDirectory directory = new();
        string path = directory.Combine(CoverageFile.FILE_NAME);

        CoverageRowUpdate update = await UpdateFileAsync(path: path, cancellationToken: this.CancellationToken());

        Assert.Equal(expected: CoverageRowOutcome.NoTable, actual: update.Outcome);
        Assert.False(condition: File.Exists(path), userMessage: "only a file with a table is updated");
    }

    private static ValueTask<CoverageRowUpdate> UpdateFileAsync(
        string path,
        System.Threading.CancellationToken cancellationToken
    )
    {
        return CoverageFile.UpdateRowAsync(
            path: path,
            language: CoverageLanguage.Dotnet,
            row: CoverageRow.Measured("Example.Api", 9, 10),
            headSha: SHA,
            capturedOn: CapturedOn,
            timeProvider: TimeProvider.System,
            cancellationToken: cancellationToken
        );
    }

    private static CoverageRowUpdate Update(string existing, CoverageRow row)
    {
        return CoverageFile.UpdateRow(
            existing: existing,
            language: CoverageLanguage.Dotnet,
            row: row,
            headSha: SHA,
            capturedOn: CapturedOn
        );
    }

    private static string FullRun(params AssemblyCoverage[] assemblies)
    {
        return HEADER + Section(assemblies) + "\n" + NODE_AND_SHELL + NEW_FOOTER;
    }

    private static string Section(params AssemblyCoverage[] assemblies)
    {
        return CoverageMarkdown.FormatSection(summary: Summary(assemblies), language: CoverageLanguage.Dotnet);
    }

    private static AssemblyCoverage Measured(string name, int covered, int valid, double lineCoverage)
    {
        return new(Name: name, LinesCovered: covered, LinesValid: valid, LineCoverage: lineCoverage);
    }

    private static CoverageSummary Summary(params AssemblyCoverage[] assemblies)
    {
        int covered = 0;
        int valid = 0;

        foreach (AssemblyCoverage assembly in assemblies)
        {
            covered += assembly.LinesCovered;
            valid += assembly.LinesValid;
        }

        return new(
            Assemblies: assemblies,
            Overall: new(Name: CoverageAggregator.OVERALL, LinesCovered: covered, LinesValid: valid, LineCoverage: 0d)
        );
    }
}
