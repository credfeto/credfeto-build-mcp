using System;
using System.IO;
using System.Threading.Tasks;
using Credfeto.Build.Core.Coverage;
using Credfeto.Build.Testing;
using FunFair.Test.Common;
using Xunit;

namespace Credfeto.Build.Core.Tests.Coverage;

public sealed class CoverageSectionTests : TestBase
{
    private const string SHA = "0123456789abcdef0123456789abcdef01234567";

    private const string HEADER = "# Coverage\n\nGenerated by the AI Coverage phase. Do not edit by hand.\n\n";

    private const string DOTNET =
        "## .NET\n\n| Project | Line Coverage | Covered | Coverable |\n| --- | --- | --- | --- |\n| Example.Core | 80.0% | 4 | 5 |\n| **Overall (.NET)** | **80.0%** | **4** | **5** |\n";

    private const string NODE =
        "## Node\n\n| Package | Line Coverage | Covered | Coverable |\n| --- | --- | --- | --- |\n| web | 75.0% | 3 | 4 |\n| **Overall (Node)** | **75.0%** | **3** | **4** |\n";

    private const string PYTHON_AND_SHELL = "## Python\n\nn/a (no code)\n\n## Shell\n\nexcluded\n\n";

    private const string PYTHON =
        "## Python\n\n| Package | Line Coverage | Covered | Coverable |\n| --- | --- | --- | --- |\n| tools | 50.0% | 1 | 2 |\n| **Overall (Python)** | **50.0%** | **1** | **2** |\n";

    private const string SHELL = "## Shell\n\nexcluded\n\n";

    private const string OLD_FOOTER = "---\n\nCaptured at commit `old` on 2026-01-01.\n";

    private const string NEW_FOOTER = "---\n\nCaptured at commit `" + SHA + "` on 2026-11-16.\n";

    private static readonly DateOnly CapturedOn = new(year: 2026, month: 11, day: 16);

    [Fact]
    public static void TheNodeSectionHasItsOwnHeadingColumnAndOverallRow()
    {
        CoverageSummary summary = new(
            Assemblies: [new(Name: "web", LinesCovered: 3, LinesValid: 4, LineCoverage: 75d)],
            Overall: new(Name: CoverageAggregator.OVERALL, LinesCovered: 3, LinesValid: 4, LineCoverage: 75d)
        );

        Assert.Equal(
            expected: NODE,
            actual: CoverageMarkdown.FormatSection(summary: summary, language: CoverageLanguage.Node)
        );
    }

    [Fact]
    public static void ANewNodeSectionGoesAfterDotnetAndBeforePython()
    {
        Assert.Equal(
            expected: HEADER + DOTNET + "\n" + NODE + "\n" + PYTHON_AND_SHELL + NEW_FOOTER,
            actual: MergeNode(HEADER + DOTNET + "\n" + PYTHON_AND_SHELL + OLD_FOOTER)
        );
    }

    [Fact]
    public static void ANewNodeSectionGoesFirstWhenThereIsNoDotnetSection()
    {
        Assert.Equal(
            expected: HEADER + NODE + "\n" + PYTHON_AND_SHELL + NEW_FOOTER,
            actual: MergeNode(HEADER + PYTHON_AND_SHELL + OLD_FOOTER)
        );
    }

    [Fact]
    public static void ANewNodeSectionGoesAfterDotnetWhenNothingFollows()
    {
        Assert.Equal(
            expected: HEADER + DOTNET + "\n" + NODE + "\n" + NEW_FOOTER,
            actual: MergeNode(HEADER + DOTNET + "\n" + OLD_FOOTER)
        );
    }

    [Fact]
    public static void ANewNodeSectionGoesBeforeAHeadingItDoesNotKnowThatFollowsDotnet()
    {
        const string notes = "## Notes\n\nkept\n\n";

        Assert.Equal(
            expected: HEADER + DOTNET + "\n" + NODE + "\n" + notes + NEW_FOOTER,
            actual: MergeNode(HEADER + DOTNET + "\n" + notes + OLD_FOOTER)
        );
    }

    [Fact]
    public static void ThePythonSectionHasItsOwnHeadingColumnAndOverallRow()
    {
        CoverageSummary summary = new(
            Assemblies: [new(Name: "tools", LinesCovered: 1, LinesValid: 2, LineCoverage: 50d)],
            Overall: new(Name: CoverageAggregator.OVERALL, LinesCovered: 1, LinesValid: 2, LineCoverage: 50d)
        );

        Assert.Equal(
            expected: PYTHON,
            actual: CoverageMarkdown.FormatSection(summary: summary, language: CoverageLanguage.Python)
        );
    }

    [Fact]
    public static void ANewPythonSectionGoesAfterNodeAndBeforeShell()
    {
        Assert.Equal(
            expected: HEADER + DOTNET + "\n" + NODE + "\n" + PYTHON + "\n" + SHELL + NEW_FOOTER,
            actual: MergePython(HEADER + DOTNET + "\n" + NODE + "\n" + SHELL + OLD_FOOTER)
        );
    }

    [Fact]
    public static void AHandWrittenPythonSectionIsReplacedAndEveryOtherSectionIsLeftAlone()
    {
        const string handWritten =
            "## Python\n\n| Package | Line Coverage |\n| --- | --- |\n| scripts/check | 98.5% |\n| **Overall (Python)** | **98.5%** |\n\n";

        Assert.Equal(
            expected: HEADER + DOTNET + "\n" + NODE + "\n" + PYTHON + "\n" + SHELL + NEW_FOOTER,
            actual: MergePython(HEADER + DOTNET + "\n" + NODE + "\n" + handWritten + SHELL + OLD_FOOTER)
        );
    }

    [Fact]
    public static void TheNodeSectionIsReplacedAndEveryOtherSectionIsLeftAlone()
    {
        Assert.Equal(
            expected: HEADER + DOTNET + "\n" + NODE + "\n" + PYTHON_AND_SHELL + NEW_FOOTER,
            actual: MergeNode(HEADER + DOTNET + "\n## Node\n\nn/a (no code)\n\n" + PYTHON_AND_SHELL + OLD_FOOTER)
        );
    }

    [Fact]
    public static void ADotnetWriteLeavesTheNodeSectionAlone()
    {
        Assert.Equal(
            expected: HEADER + DOTNET + "\n" + NODE + "\n" + NEW_FOOTER,
            actual: CoverageFile.Merge(
                existing: HEADER + "## .NET\n\nold\n\n" + NODE + "\n" + OLD_FOOTER,
                language: CoverageLanguage.Dotnet,
                section: DOTNET,
                headSha: SHA,
                capturedOn: CapturedOn
            )
        );
    }

    [Fact]
    public async Task WritingASectionKeepsTheOtherLanguagesSectionAsync()
    {
        using TemporaryDirectory directory = new();
        string path = await directory.WriteAsync(
            relative: CoverageFile.FILE_NAME,
            content: HEADER + DOTNET + "\n" + OLD_FOOTER,
            cancellationToken: this.CancellationToken()
        );

        await WriteNodeAsync(path: path, cancellationToken: this.CancellationToken());

        Assert.Equal(
            expected: HEADER + DOTNET + "\n" + NODE + "\n" + NEW_FOOTER,
            actual: await File.ReadAllTextAsync(path: path, cancellationToken: this.CancellationToken())
        );
    }

    [Fact]
    public async Task WritingASectionCreatesAMissingFileAsync()
    {
        using TemporaryDirectory directory = new();
        string path = directory.Combine(CoverageFile.FILE_NAME);

        await WriteNodeAsync(path: path, cancellationToken: this.CancellationToken());

        Assert.Equal(
            expected: HEADER + NODE + "\n" + NEW_FOOTER,
            actual: await File.ReadAllTextAsync(path: path, cancellationToken: this.CancellationToken())
        );
    }

    [Fact]
    public async Task AWriterWaitsForAnotherWriterAndBothSectionsSurviveAsync()
    {
        using TemporaryDirectory directory = new();
        string path = directory.Combine(CoverageFile.FILE_NAME);
        Task waiting;

        await using (
            FileStream other = new(
                path: path,
                mode: FileMode.CreateNew,
                access: FileAccess.ReadWrite,
                share: FileShare.None
            )
        )
        {
            waiting = WriteNodeAsync(path: path, cancellationToken: this.CancellationToken()).AsTask();

            await Task.Delay(delay: TimeSpan.FromMilliseconds(500), cancellationToken: this.CancellationToken());
            Assert.False(condition: waiting.IsCompleted, userMessage: "the second writer waits for the first");

            // The first writer's .NET section, written while it holds the file
            byte[] first = System.Text.Encoding.UTF8.GetBytes(HEADER + DOTNET + "\n" + OLD_FOOTER);
            await other.WriteAsync(buffer: first, cancellationToken: this.CancellationToken());
        }

        await waiting;

        Assert.Equal(
            expected: HEADER + DOTNET + "\n" + NODE + "\n" + NEW_FOOTER,
            actual: await File.ReadAllTextAsync(path: path, cancellationToken: this.CancellationToken())
        );
    }

    private static ValueTask WriteNodeAsync(string path, System.Threading.CancellationToken cancellationToken)
    {
        return CoverageFile.WriteSectionAsync(
            path: path,
            language: CoverageLanguage.Node,
            section: NODE,
            headSha: SHA,
            capturedOn: CapturedOn,
            timeProvider: TimeProvider.System,
            cancellationToken: cancellationToken
        );
    }

    private static string MergeNode(string existing)
    {
        return Merge(existing: existing, language: CoverageLanguage.Node, section: NODE);
    }

    private static string MergePython(string existing)
    {
        return Merge(existing: existing, language: CoverageLanguage.Python, section: PYTHON);
    }

    private static string Merge(string existing, CoverageLanguage language, string section)
    {
        return CoverageFile.Merge(
            existing: existing,
            language: language,
            section: section,
            headSha: SHA,
            capturedOn: CapturedOn
        );
    }
}
