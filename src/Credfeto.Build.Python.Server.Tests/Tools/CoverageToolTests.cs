namespace Credfeto.Build.Python.Server.Tests.Tools;

public sealed class CoverageToolTests : TestBase, IDisposable
{
    // What coverage.py 7.17 writes for a one-module project and its tests
    private const string COVERAGE_PY_REPORT = """
        <?xml version="1.0" ?>
        <coverage version="7.17.5" timestamp="1795547446059" lines-valid="9" lines-covered="8" line-rate="0.8889" branches-covered="0" branches-valid="0" branch-rate="0" complexity="0">
            <!-- Generated by coverage.py: https://coverage.readthedocs.io/en/7.17.5 -->
            <sources>
                <source>/tmp/calc</source>
            </sources>
            <packages>
                <package name="." line-rate="0.75" branch-rate="0" complexity="0">
                    <classes>
                        <class name="calc.py" filename="calc.py" complexity="0" line-rate="0.75" branch-rate="0">
                            <methods/>
                            <lines>
                                <line number="4" hits="1"/>
                                <line number="6" hits="1"/>
                                <line number="9" hits="1"/>
                                <line number="11" hits="0"/>
                            </lines>
                        </class>
                    </classes>
                </package>
                <package name="tests" line-rate="1" branch-rate="0" complexity="0">
                    <classes>
                        <class name="test_calc.py" filename="tests/test_calc.py" complexity="0" line-rate="1" branch-rate="0">
                            <methods/>
                            <lines>
                                <line number="2" hits="1"/>
                                <line number="5" hits="1"/>
                                <line number="7" hits="1"/>
                                <line number="10" hits="1"/>
                                <line number="12" hits="1"/>
                            </lines>
                        </class>
                    </classes>
                </package>
            </packages>
        </coverage>
        """;

    private readonly JobToolFixture _fixture = new();

    public void Dispose()
    {
        this._fixture.Dispose();
    }

    [Fact]
    public async Task AllProjectsRunCoverageAndAlwaysWriteThePythonSectionAsync()
    {
        await this.ProjectAsync();
        string staleReport = await this._fixture.Repository.WriteAsync(
            relative: ".venv/.credfeto-build-python-coverage.xml",
            content: "<coverage/>",
            cancellationToken: this.CancellationToken()
        );

        CallToolResult result = await this.CoverageAsync("all");

        Assert.False(condition: result.IsError, userMessage: TestTools.Text(result));
        JobDefinition job = this._fixture.Runner.Started.Single();
        Assert.Equal(
            expected: ["coverage example", "coverage report example"],
            actual: job.Steps.Select(static step => step.Name),
            comparer: StringComparer.Ordinal
        );
        Assert.Equal(
            expected: ["-m", "coverage", "run", "-m", "pytest", "-p", "no:cacheprovider", "--color=no", "-rfE"],
            actual: job.Steps[0].Arguments,
            comparer: StringComparer.Ordinal
        );
        Assert.Equal(
            expected: ["-m", "coverage", "xml", "-o", staleReport],
            actual: job.Steps[1].Arguments,
            comparer: StringComparer.Ordinal
        );
        Assert.Equal(
            expected: this._fixture.Repository.Combine(".venv/.credfeto-build-python-coverage"),
            actual: job.Steps[0].Environment["COVERAGE_FILE"]
        );
        Assert.True(
            condition: job.Steps.All(static step => step.StopJobOnFailure),
            userMessage: "a failed run makes no report"
        );
        Assert.Equal(expected: [staleReport], actual: job.CoverageFiles, comparer: StringComparer.Ordinal);
        Assert.Equal(expected: "example", actual: job.CoverageComponents?[staleReport]);
        Assert.Same(expected: CoverageLanguage.Python, actual: job.CoverageLanguage);
        Assert.Equal(expected: this._fixture.Repository.Combine("COVERAGE.md"), actual: job.CoverageReportPath);
        Assert.Null(job.CoverageReportComponent);
        Assert.IsType<PytestOutputParser>(job.TestParser);
        Assert.False(condition: File.Exists(staleReport), userMessage: "an earlier report is never read as this run's");
    }

    [Fact]
    public async Task ASingleProjectRunReplacesOnlyItsRowAsync()
    {
        await this.ProjectAsync();

        CallToolResult result = await this.CoverageAsync("example");

        Assert.False(condition: result.IsError, userMessage: TestTools.Text(result));
        JobDefinition job = this._fixture.Runner.Started.Single();
        Assert.Equal(expected: "example", actual: job.CoverageReportComponent);
        Assert.Equal(expected: this._fixture.Repository.Combine("COVERAGE.md"), actual: job.CoverageReportPath);
    }

    [Fact]
    public async Task ACoveragePyReportIsOneRowPerProjectAsync()
    {
        await using MemoryStream stream = new(Encoding.UTF8.GetBytes(COVERAGE_PY_REPORT));
        CoberturaReport report = await CoberturaParser.ParseAsync(
            stream: stream,
            cancellationToken: this.CancellationToken()
        );

        CoverageSummary summary = CoverageAggregator.Combine([report.AsComponent("calc")]);

        Assert.Equal(
            expected: "## Python\n\n| Package | Line Coverage | Covered | Coverable |\n| --- | --- | --- | --- |\n| calc | 88.9% | 8 | 9 |\n| **Overall (Python)** | **88.9%** | **8** | **9** |\n",
            actual: CoverageMarkdown.FormatSection(summary: summary, language: CoverageLanguage.Python)
        );
    }

    private async ValueTask ProjectAsync()
    {
        await PythonRepositories.InitGitAsync(
            repository: this._fixture.Repository,
            cancellationToken: this.CancellationToken()
        );
        await PythonRepositories.WriteAsync(
            repository: this._fixture.Repository,
            cancellationToken: this.CancellationToken()
        );
        PythonDetection detection = await PythonDetector.DetectAsync(
            repositoryRoot: this._fixture.Repository.Path,
            cancellationToken: this.CancellationToken()
        );
        PythonProject project = detection.Repository?.Projects.Single()
            ?? throw new InvalidOperationException("no project");
        VirtualEnvironment environment = VirtualEnvironment.For(
            repositoryRoot: this._fixture.Repository.Path,
            project: project
        );
        string stamp = await VirtualEnvironment.StampAsync(
            environment: environment,
            project: project,
            interpreter: "/usr/bin/python3",
            version: new(Major: 3, Minor: 13, Patch: 1),
            cancellationToken: this.CancellationToken()
        );
        _ = await this._fixture.Repository.WriteAsync(
            relative: ".venv/bin/python",
            content: string.Empty,
            cancellationToken: this.CancellationToken()
        );
        _ = await this._fixture.Repository.WriteAsync(
            relative: ".venv/" + VirtualEnvironment.STAMP_FILE,
            content: stamp,
            cancellationToken: this.CancellationToken()
        );
    }

    private ValueTask<CallToolResult> CoverageAsync(string package)
    {
        return this._fixture.CallAsync(
            tool: ToolNames.COVERAGE,
            arguments: TestTools.Arguments(("package", package)),
            cancellationToken: this.CancellationToken()
        );
    }
}
